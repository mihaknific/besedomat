export type LangKey = keyof I18nData;

export function getI(key: string, lang: LangKey = 'en'): string {
  const langData = I18N[lang] ? I18N[lang] : I18N.en;
  const val = langData && langData[key];
  if (val != null) return val;
  if (I18N.en && I18N.en[key] != null) return I18N.en[key];
  return key;
}
